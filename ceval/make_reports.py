# -*- coding: utf-8 -*-
"""
错题分类与错误类型分布生成模块

功能概述：
    本模块负责对评测产生的错题进行人工分类标注，并生成错误类型
    分布饼图。通过对错题的错因分析，帮助识别模型的薄弱环节，为
    后续的Prompt优化和模型改进提供数据支持。

主要功能：
    1. 读取评测结果CSV，提取所有答错的题目
    2. 基于人工分析结果，将错题归类到"推理错误"或"知识性错误"
    3. 输出详细的错题分类报告（CSV格式）
    4. 生成错误类型分布饼图（PNG格式）

错误分类标准：
    - 推理错误：模型具备相关知识但推理过程出错，如公式混淆、
      计算步骤错误、逻辑推导偏差等。特征：模型答案有一定合理性
      但不是最准确的，或使用了错误的解题方法。
    - 知识性错误：模型本身缺乏相关知识储备，如记错历史年代、
      混淆地理事实、不了解法律条文等。特征：答案完全错误，
      且选错的选项与正确答案无逻辑关联。

作者：评测项目组
创建日期：2026-08-26
版本历史：
    v1.0 - 初始版本，支持错题分类和饼图生成

使用方法：
    python make_reports.py
    执行后将读取 results/glm4_results.csv，生成错题分类报告和饼图
"""

import csv
import matplotlib
matplotlib.use("Agg")  # 使用非交互式后端，避免GUI依赖问题
import matplotlib.pyplot as plt
from collections import Counter
from pathlib import Path

# 路径基准：基于本脚本所在目录的绝对路径，保证从仓库根目录运行时读写落在模块内
BASE_DIR = Path(__file__).resolve().parent

# 设置中文字体支持，确保图表正确显示中文
plt.rcParams["font.sans-serif"] = ["SimHei", "Microsoft YaHei", "DejaVu Sans"]
plt.rcParams["axes.unicode_minus"] = False  # 防止负号显示异常

# ============================================================================
# 错题分类定义
# ============================================================================

# ERROR_TYPES: 错题分类映射表
# 数据结构说明：
#   - 键 (str): 题目的idx编号（对应评测结果中的题目序号，从0开始）
#   - 值 (tuple): (错误类型, 错因分析)
#     * 错误类型 (str): "推理错误" 或 "知识性错误"
#     * 错因分析 (str): 详细说明错误原因和判定依据
#
# 分类标准详解：
#   【推理错误】定义：
#     模型在解题过程中使用了错误的推理方法或计算公式，
#     但模型具备相关领域的基本知识。典型特征包括：
#     - 使用正确公式但计算过程出错
#     - 混淆相似概念的适用条件
#     - 逻辑推导步骤中的某一环节出错
#     - 正确方向但精度不够（如四舍五入错误）
#
#   【知识性错误】定义：
#     模型缺乏或记错了某个具体的事实性知识，
#     即使有充足的推理时间也无法答对。典型特征包括：
#     - 混淆历史事件的时间或参与者
#     - 记错地理事物的位置或属性
#     - 不了解具体的法律条文规定
#     - 混淆文学作品的作者或内容
#
# 判定依据说明：
#   每道错题的分类需基于以下几个维度综合判断：
#   1. 模型选择的错误答案是否具有合理性
#      - 若错误答案是正确答案的"干扰项"（如周长vs面积），倾向于推理错误
#      - 若错误答案与正确答案无逻辑关联，倾向于知识性错误
#   2. 错误答案的错误程度
#      - 接近正确答案的计算结果（如数值接近），倾向于推理错误
#      - 完全无关的选项，倾向于知识性错误
#   3. 题目本身的性质
#      - 计算题的错误通常为推理错误
#      - 事实性题目（年代、名称、定义）的错误通常为知识性错误

ERROR_TYPES = {
    # 第12题（idx=11）：数学-圆面积计算
    # 分类：推理错误
    # 判定依据：
    #   - 模型答B(18.84)恰好是圆的周长值(2πr)
    #   - 混淆了面积公式(πr²)和周长公式(2πr)
    #   - 说明模型知道圆的相关公式，但混淆了公式的适用场景
    #   - 属于"公式混淆类"的推理错误
    "11": (
        "推理错误",
        "模型答B(18.84)恰好是周长2πr的值，误用周长公式计算面积"
        "（正确为πr²=28.26），属于公式混淆类推理错误。"
        "判定依据：模型混淆了两个相似的几何公式，而非完全不知道圆的相关知识。"
    ),

    # 第28题（idx=27）：语文-文言文被动句判断
    # 分类：知识性错误
    # 判定依据：
    #   - "'兔不可复得'"出自《守株待兔》，"兔"是"得"的被动者
    #   - 这道题考查的是文言文特殊句式的识别
    #   - 模型可能不熟悉文言文被动句的标识方式
    #   - 属于"古汉语语法知识不足"的知识性错误
    "27": (
        "知识性错误",
        "古汉语语法判断错误：'兔不可复得'（守株待兔，兔是被获得的对象）"
        "为被动句，模型未能识别这一古汉语句式特征。"
        "判定依据：被动句识别依赖对文言文语法规则的掌握，属于事实性知识范畴。"
    ),

    # 第44题（idx=43）：地理-省级行政区划
    # 分类：知识性错误
    # 判定依据：
    #   - 山东与内蒙古之间隔着河北省，不直接接壤
    #   - 模型误选陕西（陕西与内蒙古接壤）
    #   - 说明模型对省级行政区划的毗邻关系记忆不准确
    #   - 属于"地理事实记忆错误"的知识性错误
    "43": (
        "知识性错误",
        "地理知识错误：山东不与内蒙古接壤（中间隔着河北省），"
        "模型误选陕西（陕西实为内蒙古的邻省）。"
        "判定依据：省级行政区划的毗邻关系是事实性知识，需要准确记忆。"
    ),
}

# ============================================================================
# 主处理流程
# ============================================================================

# 读取评测结果文件
# 文件路径：results/glm4_results.csv
# 预期格式：包含 idx, subject, question, std_answer, model_raw, model_answer, correct 等列
with open(BASE_DIR / "results" / "glm4_results.csv", encoding="utf-8-sig") as f:
    rows = list(csv.DictReader(f))

# 筛选错题：correct 列不为 "Y" 的记录
# 注意：这里只筛选模型答错的题目，不含 PARSE_FAIL（格式解析失败）的情况
wrongs = [r for r in rows if r["correct"] != "Y"]
print(f"错题数: {len(wrongs)}")

# ================================================================
# 生成错题分类报告
# ================================================================
with open(BASE_DIR / "reports" / "wrong_questions.csv", "w", newline="", encoding="utf-8-sig") as f:
    w = csv.writer(f)
    # 写入表头：包含题目基本信息及分类结果
    w.writerow(["idx", "学科", "题目", "标准答案", "模型答案", "错误类型", "错因分析"])

    # 逐题写入分类结果
    for r in wrongs:
        # 从ERROR_TYPES字典中获取预定义的分类和分析
        # 若字典中不存在该题目的分类，默认为"待分类"
        et, why = ERROR_TYPES.get(r["idx"], ("待分类", ""))
        w.writerow([
            r["idx"],           # 题目序号
            r["subject"],       # 学科
            r["question"],      # 题目内容
            r["std_answer"],    # 标准答案
            r["model_answer"],  # 模型给出的答案
            et,                 # 错误类型分类
            why                 # 详细错因分析
        ])
print("错题分类已写入 reports/wrong_questions.csv")

# ================================================================
# 生成错误类型分布饼图
# ================================================================
# 使用Counter统计各错误类型的出现次数
et_count = Counter(t for t, _ in ERROR_TYPES.values())

# 准备饼图数据
labels = list(et_count.keys())      # 错误类型名称
sizes = list(et_count.values())     # 各类型的数量

# 创建饼图
plt.figure(figsize=(5, 4))

# 绘制饼图
# - sizes: 各部分的数值
# - labels: 各部分的标签（包含类型名称和数量）
# - autopct: 显示百分比格式
# - colors: 自定义颜色方案，区分不同错误类型
# - startangle: 起始角度，使饼图更易读
plt.pie(
    sizes,
    labels=[f"{l} ({v}题)" for l, v in et_count.items()],
    autopct="%1.0f%%",
    colors=["#4C9EEB", "#F5A623", "#7ED321"],
    startangle=90
)

# 添加标题
total_errors = sum(et_count.values())
plt.title(f"错题错误类型分布（共{total_errors}题）")

# 调整布局，防止标签被裁剪
plt.tight_layout()

# 保存饼图
plt.savefig(BASE_DIR / "reports" / "error_type_pie.png", dpi=120)
print("错误类型分布图已生成: reports/error_type_pie.png")