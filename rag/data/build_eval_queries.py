# B 类口语化改写：模板轮换 + 口语词替换表（确定性，可复现）
# ---------------------------------------------------------------------------
_TEMPLATES = [
    "想了解下，{q}",
    "问一下哈，{q}",
    "请问{q}",
    "帮我看看，{q}",
    "麻烦说下{q}",
    "{q}？想确认一下",
    "有人知道{q}吗",
    "咨询个事，{q}",
    "想问下{q}，谢谢",
    "你好，{q}？",
]
_WORD_SUBS = [  # (原词, 口语替代) 逐条命中即替换，模拟真实口语表达
    ("多少", "多少"), ("是哪一年", "哪年"), ("隶属于", "属于"), ("比例是多少", "比例是多少"),
    ("是多少", "多少呀"), ("有哪几种", "有哪几种"), ("要提前", "得提前"), ("需要", "要不要"),
    ("可以", "能不能"), ("怎么补偿", "咋算"), ("怎么算", "咋算"), ("怎么处理", "咋办"),
]

def to_colloquial(q: str, idx: int) -> str:
    """把精确问题改写为口语化说法：轮换模板 + 有序替换，保证确定性与多样性。"""
    core = q.rstrip("？?。")
    for src, dst in _WORD_SUBS:
        if src != dst and src in core:
            core = core.replace(src, dst, 1)
            break
    tpl = _TEMPLATES[idx % len(_TEMPLATES)]
    out = tpl.format(q=core)
    return out if out.endswith(("？", "?")) else out + ("？" if not tpl.endswith("？") else "")

